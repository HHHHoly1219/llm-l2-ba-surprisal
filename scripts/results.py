# 1. 自动获取所有 ba_preferred 结果文件
ba_files = glob.glob("*_ba_preferred_results.csv")
h2_summary = []

print(f"🔍 准备处理 {len(ba_files)} 个模型的 H2 数据...\n")

for ba_file in ba_files:
    model_name = ba_file.replace("_ba_preferred_results.csv", "")
    svo_file = f"{model_name}_svo_preferred_results.csv"

    if not os.path.exists(svo_file):
        continue

    # 读取数据
    df_ba = pd.read_csv(ba_file)
    df_svo = pd.read_csv(svo_file)

    # ==========================================
    # 🌟 关键修复 1：剔除含有 NaN 的极短句子题目 (Listwise Deletion)
    # ==========================================
    # 记录原始数据量
    original_len = len(df_svo)

    # 剔除 SVO 文件中的空值
    df_svo = df_svo.dropna(subset=['noctx_svo_mean_surp'])

    # 提取剔除后剩下的健康题目的 ID
    valid_svo_ids = df_svo['example_id'].tolist()

    # 对 BA 文件执行严格对齐：也剔除那些因为 noctx_svo 空值而被牵连的题
    # 同时剔除 BA 自身可能存在的 noctx 空值
    df_ba = df_ba.dropna(subset=['noctx_ba_mean_surp'])
    valid_ba_ids = df_ba['example_id'].tolist()

    # 取交集，保证两边完全对称
    final_valid_ids = list(set(valid_svo_ids) & set(valid_ba_ids))
    df_ba = df_ba[df_ba['example_id'].isin(final_valid_ids)]
    df_svo = df_svo[df_svo['example_id'].isin(final_valid_ids)]

    if original_len != len(df_svo):
        print(f"[{model_name}] 剔除了 {original_len - len(df_svo)} 个包含 NaN 的极短文本题目。")

    # ==========================================
    # 🌟 关键修复 2：使用模糊匹配 (contains) 计算反转率
    # ==========================================
    # BA 组反转：无语境时偏好 SVO，有语境后变为偏好把字句
    ba_reversals = ((df_ba['noctx_prefer_mean'].str.contains('SVO', case=False, na=False)) &
                    (df_ba['ctx_prefer_mean'].str.contains('把字句', na=False))).sum() / len(df_ba) * 100

    # SVO 组反转：无语境时偏好把字句，有语境后变为偏好 SVO
    svo_reversals = ((df_svo['noctx_prefer_mean'].str.contains('把字句', na=False)) &
                     (df_svo['ctx_prefer_mean'].str.contains('SVO', case=False, na=False))).sum() / len(df_svo) * 100

    # ==========================================
    # 计算 H2 指标 1: Δ Surprisal 及 T 检验
    # ==========================================
    # BA语境下
    delta_ba = df_ba['noctx_ba_mean_surp'] - df_ba['ctx_ba_mean_surp']
    t_ba, p_ba = stats.ttest_rel(df_ba['noctx_ba_mean_surp'], df_ba['ctx_ba_mean_surp'])

    # SVO语境下
    delta_svo = df_svo['noctx_svo_mean_surp'] - df_svo['ctx_svo_mean_surp']
    t_svo, p_svo = stats.ttest_rel(df_svo['noctx_svo_mean_surp'], df_svo['ctx_svo_mean_surp'])

    # 记录到总表
    h2_summary.append({
        'Model': model_name,
        'BA Δ Surprisal': round(delta_ba.mean(), 3),
        'BA t-value': round(t_ba, 3),
        'BA p-value': p_ba,
        'BA Reversal Rate (%)': round(ba_reversals, 1),
        'SVO Δ Surprisal': round(delta_svo.mean(), 3),
        'SVO t-value': round(t_svo, 3),
        'SVO p-value': p_svo,
        'SVO Reversal Rate (%)': round(svo_reversals, 1)
    })

# 生成 DataFrame 并按 BA Reversal Rate 降序排序
df_h2 = pd.DataFrame(h2_summary).sort_values(by='BA Reversal Rate (%)', ascending=False)
df_h2.to_csv("H2_Context_Coercion_Summary_Fixed.csv", index=False, encoding='utf-8-sig')


