    ax = sns.boxplot(x="Context Type", y="Mean Surprisal", hue="Sentence Form", data=df_plot,
                     palette=my_palette, showfliers=False, width=0.6, boxprops=dict(alpha=0.8))
    sns.stripplot(x="Context Type", y="Mean Surprisal", hue="Sentence Form", data=df_plot,
                  palette=my_palette, dodge=True, alpha=0.4, size=4, ax=ax)

    # 手工绘制显著性星号连线
    def draw_significance(ax, x1, x2, y_max, h, text):
        ax.plot([x1, x1, x2, x2], [y_max, y_max+h, y_max+h, y_max], lw=1.5, color='black')
        ax.text((x1+x2)*.5, y_max+h, text, ha='center', va='bottom', color='black', fontsize=14, fontweight='bold')

    y_max = df_plot['Mean Surprisal'].max()
