import os
import glob
import pandas as pd
import scipy.stats as stats
import matplotlib.pyplot as plt
import seaborn as sns

# 1. 获取所有 ba_preferred 结果文件
ba_files = glob.glob("*_ba_preferred_results.csv")
h3_summary = []

print(f"🔍 正在处理 {len(ba_files)} 个模型的 H3 数据（句级 vs. 首词级）...\n")

for ba_file in ba_files:
    model_name = ba_file.replace("_ba_preferred_results.csv", "")
    svo_file = f"{model_name}_svo_preferred_results.csv"
    if not os.path.exists(svo_file): continue

    # 读取数据
    df_ba = pd.read_csv(ba_file)
    df_svo = pd.read_csv(svo_file)

    # ==========================================
    # 🌟 核心 Bug 修复区：清理 "正确_把字句" 等格式
    # ==========================================
    # BA 语境：标准答案应该是偏好把字句 (包含 '把字句' 即可)
    # 句级正确量
    ba_sent_correct = df_ba['ctx_prefer_mean'].str.contains('把字句', na=False).sum()
    # 首词级正确量
    ba_token_correct = df_ba['ctx_prefer_first_token'].str.contains('把字句', na=False).sum()

    # SVO 语境：标准答案应该是偏好SVO (包含 'SVO' 即可, 忽略大小写)
    # 句级正确量
    svo_sent_correct = df_svo['ctx_prefer_mean'].str.contains('SVO', case=False, na=False).sum()
    # 首词级正确量
    svo_token_correct = df_svo['ctx_prefer_first_token'].str.contains('SVO', case=False, na=False).sum()

    # 计算总题数
    total_items = len(df_ba) + len(df_svo)

    # 整体准确率
    sent_acc = (ba_sent_correct + svo_sent_correct) / total_items * 100
    token_acc = (ba_token_correct + svo_token_correct) / total_items * 100

    h3_summary.append({
        'Model': model_name,
        'Sentence-Level Acc (%)': sent_acc,
        'First-Token Acc (%)': token_acc
    })

# 生成 DataFrame
df_h3 = pd.DataFrame(h3_summary)
df_h3.to_csv("H3_Granularity_Comparison_Fixed.csv", index=False, encoding='utf-8-sig')

# ==========================================
# 统计显著性检验 (Paired t-test)
# ==========================================
t_stat, p_val = stats.ttest_rel(df_h3['Sentence-Level Acc (%)'], df_h3['First-Token Acc (%)'])

print("=== H3: Paired T-test Results (Across Models) ===")
print(f"Mean Sentence Acc: {df_h3['Sentence-Level Acc (%)'].mean():.2f}%")
print(f"Mean First-Token Acc: {df_h3['First-Token Acc (%)'].mean():.2f}%")
print(f"T-statistic = {t_stat:.4f}, p-value = {p_val:.4e}")
if p_val < 0.05 and t_stat > 0:
    print("✅ 结论: Sentence-level 准确率显著高于 First-token 准确率！\n")

# ==========================================
