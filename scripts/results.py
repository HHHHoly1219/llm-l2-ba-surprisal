import pandas as pd
import scipy.stats as stats
import matplotlib.pyplot as plt
import seaborn as sns

# 1. 自动获取所有 ba_preferred 文件
ba_files = glob.glob("*_ba_preferred_results.csv")

# 准备一个列表，用来存储 23 个模型的 T 检验结果，最后导出为总表
stats_summary = []

print(f"🔍 共检测到 {len(ba_files)} 个模型的测试数据。开始批量处理...\n")

for ba_file in ba_files:
    # 从文件名中提取当前模型名称 (例如: "Qwen3-14B-Base")
    model_name = ba_file.replace("_ba_preferred_results.csv", "")
    svo_file = f"{model_name}_svo_preferred_results.csv"

    # 检查对应的 svo 文件是否存在
    if not os.path.exists(svo_file):
        print(f"⚠️ 找不到 {model_name} 对应的 SVO 文件，跳过此模型。")
        continue

    print(f"📊 正在分析并绘制: {model_name}")

    # 读取数据
    df_ba = pd.read_csv(ba_file)
    df_svo = pd.read_csv(svo_file)

    # 2. 统计显著性检验 (Paired t-test)
    t_ba, p_ba = stats.ttest_rel(df_ba['ctx_ba_mean_surp'], df_ba['ctx_svo_mean_surp'])
    t_svo, p_svo = stats.ttest_rel(df_svo['ctx_ba_mean_surp'], df_svo['ctx_svo_mean_surp'])

    # 将结果保存到总表字典中
    stats_summary.append({
        'Model': model_name,
        'BA-Pref Context: t-value': round(t_ba, 4),
        'BA-Pref Context: p-value': p_ba,
        'BA-Pref Significant?': 'Yes (***)' if p_ba < 0.001 else ('Yes (*)' if p_ba < 0.05 else 'No'),
        'SVO-Pref Context: t-value': round(t_svo, 4),
        'SVO-Pref Context: p-value': p_svo,
        'SVO-Pref Significant?': 'Yes (***)' if p_svo < 0.001 else ('Yes (*)' if p_svo < 0.05 else 'No')
    })

    # 3. 整理画图数据
    plot_data = []
    for i, row in df_ba.iterrows():
        plot_data.append({'Context Type': 'BA-preferred', 'Sentence Form': 'Ba-construction', 'Mean Surprisal': row['ctx_ba_mean_surp']})
        plot_data.append({'Context Type': 'BA-preferred', 'Sentence Form': 'SVO', 'Mean Surprisal': row['ctx_svo_mean_surp']})
    for i, row in df_svo.iterrows():
        plot_data.append({'Context Type': 'SVO-preferred', 'Sentence Form': 'Ba-construction', 'Mean Surprisal': row['ctx_ba_mean_surp']})
        plot_data.append({'Context Type': 'SVO-preferred', 'Sentence Form': 'SVO', 'Mean Surprisal': row['ctx_svo_mean_surp']})

