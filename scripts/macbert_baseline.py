import re
import pandas as pd

import pandas as pd

sent = pd.read_csv("macbert_baseline_results/macbert_all_400_sentence_results.csv")
pairs = pd.read_csv("macbert_baseline_results/macbert_pair_level_results.csv")

def norm(x):
    x = str(x)
    x = re.sub(r"[\s。.!！?？，,]", "", x)
    return x

inf = sent[sent["gold_label"] == "infelicitous"].copy()
inf = inf.merge(
    pairs[["pair_id", "preferred_sentence", "nonpreferred_sentence"]],
    on="pair_id",
    how="left"
)

inf["corrected_to_preferred"] = inf.apply(
    lambda r: norm(r["macbert_corrected"]) == norm(r["preferred_sentence"]),
    axis=1
)

construction_level_acc = inf["corrected_to_preferred"].mean()
construction_level_miss = 1 - construction_level_acc

print(f"Construction-level correction accuracy: {construction_level_acc:.2%}")
print(f"Construction-level miss rate: {construction_level_miss:.2%}")
print(f"N infelicitous continuations: {len(inf)}")
print(f"N corrected to preferred: {inf['corrected_to_preferred'].sum()}")