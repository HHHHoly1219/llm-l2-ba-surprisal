def load_contextual_csv(path: str, expected_context_preference: str) -> pd.DataFrame:
    df = pd.read_csv(path)
    required = {
        "global_test_id",
        "source_context_preference",
        "pair_id",
        "construction_candidate",
        "preference_in_source_context",
        "full_test_sentence",
    }
    missing = sorted(required - set(df.columns))
    if missing:
        raise ValueError(f"{path} is missing required columns: {missing}")

    # Keep only contextual rows if such a column exists.
    if "context_status" in df.columns:
        df = df[df["context_status"].astype(str).str.contains("有语境", na=False)].copy()

    # Safety check: the BA file should be BA-preferred, the SOV/SVO file should be SVO-preferred.
    observed = set(df["source_context_preference"].dropna().astype(str).unique())
    if expected_context_preference not in observed:
        print(f"[Warning] Expected {expected_context_preference} in {path}, observed: {observed}")

    return df

