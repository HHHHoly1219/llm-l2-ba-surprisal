def normalize_corrector_result(source_text: str, result: Any) -> Dict[str, Any]:
    """Normalize possible pycorrector output formats to a dict."""
    corrected = None
    errors = []

    if isinstance(result, dict):
        corrected = (
            result.get("target")
            or result.get("corrected_text")
            or result.get("correct_text")
            or result.get("corrected_sent")
            or result.get("source")
            or source_text
        )
        errors = result.get("errors", result.get("details", [])) or []

    elif isinstance(result, tuple):
        # Common old format: (corrected_text, errors)
        if len(result) >= 1:
            corrected = result[0]
        if len(result) >= 2:
            errors = result[1] or []

    elif isinstance(result, list):
        # Rare case: list of errors or [corrected, errors]
        if len(result) == 2 and isinstance(result[0], str):
            corrected = result[0]
            errors = result[1] or []
        else:
            corrected = source_text
            errors = result

    else:
        corrected = str(result) if result is not None else source_text
        errors = []

    if corrected is None:
        corrected = source_text

    # If pycorrector does not return errors but returns a changed text, count character differences as edits.
    # This is a fallback; normally MacBertCorrector returns an explicit errors list.
    if not errors and corrected != source_text:
        errors = [(src, tgt, i) for i, (src, tgt) in enumerate(zip(source_text, corrected)) if src != tgt]
        if len(corrected) != len(source_text):
            errors.append(("<length_change>", len(source_text), len(corrected)))

    return {
        "source": source_text,
        "corrected": corrected,
        "errors": errors,
        "num_errors": len(errors),
        "accepted_no_edit": len(errors) == 0,
    }


def correct_texts(texts: List[str], batch_size: int = 16) -> List[Dict[str, Any]]:
    """Run MacBERT on a list of texts. Uses correct_batch if available."""
    normalized = []

    has_batch = hasattr(corrector, "correct_batch")
    has_correct = hasattr(corrector, "correct")
    has_macbert_correct = hasattr(corrector, "macbert_correct")

    for start in tqdm(range(0, len(texts), batch_size), desc="MacBERT correcting"):
        batch_texts = texts[start:start + batch_size]

        if has_batch:
            raw_results = corrector.correct_batch(batch_texts)
            # Some versions return a single dict for one input; force list.
            if isinstance(raw_results, dict):
                raw_results = [raw_results]
            for src, res in zip(batch_texts, raw_results):
                normalized.append(normalize_corrector_result(src, res))

        else:
            for src in batch_texts:
                if has_correct:
                    res = corrector.correct(src)
                elif has_macbert_correct:
                    res = corrector.macbert_correct(src)
                else:
                    raise AttributeError("MacBertCorrector has neither correct_batch, correct, nor macbert_correct.")
                normalized.append(normalize_corrector_result(src, res))

    return normalized

