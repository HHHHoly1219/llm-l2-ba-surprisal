def run_macbert_baseline(data_ba: List[Dict], data_svo: List[Dict]) -> None:
    """
    MacBERT CSC baseline:
    - BA偏好组：检查非优选 SVO 是否被纠错模型检出
    - SVO偏好组：检查非优选 BA 是否被纠错模型检出
    """
    try:
        try:
            from pycorrector import MacBertCorrector
        except Exception:
            from pycorrector.macbert.macbert_corrector import MacBertCorrector
    except Exception as e:
        print("无法导入 MacBertCorrector，跳过 MacBERT baseline。错误：", repr(e))
        for d in data_ba:
            d["macbert_miss_svo"] = "未运行"
        for d in data_svo:
            d["macbert_miss_ba"] = "未运行"
        return

    print("\n[加载 MacBERT CSC 模型...]")
    macbert = MacBertCorrector("shibing624/macbert4csc-base-chinese")

    def get_errors(result):
        if isinstance(result, dict):
            return result.get("errors", [])
        if isinstance(result, tuple) and len(result) > 1:
            return result[1]
        return []

    for d in tqdm(data_ba, desc="MacBERT on BA-preferred group"):
        text = d["context"] + d["svo_sent"]
        result = macbert.correct(text)
        errors = get_errors(result)
        d["macbert_miss_svo"] = "漏检_认为SVO正确" if len(errors) == 0 else "检出错误"

    for d in tqdm(data_svo, desc="MacBERT on SVO-preferred group"):
        text = d["context"] + d["ba_sent"]
        result = macbert.correct(text)
        errors = get_errors(result)
        d["macbert_miss_ba"] = "漏检_认为把字句正确" if len(errors) == 0 else "检出错误"

    del macbert
    gc.collect()
    if torch.cuda.is_available():
        torch.cuda.empty_cache()


