def build_score_items_for_df(df: pd.DataFrame) -> List[ScoreItem]:
    items = []
    for idx, row in df.iterrows():
        prefix = row["context"]

        items.extend([
            ScoreItem(prefix=prefix, continuation=row["ba_sent"], row_idx=idx, key="ctx_ba"),
            ScoreItem(prefix=prefix, continuation=row["svo_sent"], row_idx=idx, key="ctx_svo"),
            ScoreItem(prefix="", continuation=row["ba_sent"], row_idx=idx, key="noctx_ba"),
            ScoreItem(prefix="", continuation=row["svo_sent"], row_idx=idx, key="noctx_svo"),
        ])
    return items


def attach_scores(df: pd.DataFrame, score_results: List[Dict]) -> pd.DataFrame:
    df = df.copy()

    for r in score_results:
        idx = r["row_idx"]
        key = r["key"]

        df.loc[idx, f"{key}_sum_surp"] = r["sum_surp"]
        df.loc[idx, f"{key}_mean_surp"] = r["mean_surp"]
        df.loc[idx, f"{key}_first_token_surp"] = r["first_token_surp"]
        df.loc[idx, f"{key}_bits_per_token"] = r["bits_per_token"]
        df.loc[idx, f"{key}_cont_token_count"] = r["continuation_token_count"]
        df.loc[idx, f"{key}_scored_token_count"] = r["scored_token_count"]

    return df


def add_preference_columns(df: pd.DataFrame, preferred: str, metric: str = "mean") -> pd.DataFrame:
    """
    preferred:
        "ba"  for BA偏好组
        "svo" for SVO偏好组
    metric:
        "mean" or "sum"
    """
    df = df.copy()

    ba_col = f"ctx_ba_{metric}_surp"
    svo_col = f"ctx_svo_{metric}_surp"

    noctx_ba_col = f"noctx_ba_{metric}_surp"
    noctx_svo_col = f"noctx_svo_{metric}_surp"

    if preferred == "ba":
        df[f"ctx_prefer_{metric}"] = df.apply(
            lambda r: "正确_把字句" if r[ba_col] < r[svo_col] else "错误_SVO",
            axis=1
        )
        df["ctx_prefer_first_token"] = df.apply(
            lambda r: "正确_把字句" if r["ctx_ba_first_token_surp"] < r["ctx_svo_first_token_surp"] else "错误_SVO",
            axis=1
        )
        df[f"noctx_prefer_{metric}"] = df.apply(
            lambda r: "把字句" if r[noctx_ba_col] < r[noctx_svo_col] else "SVO",
            axis=1
        )
        df[f"context_helped_{metric}"] = df.apply(
            lambda r: "是" if r[ba_col] < r[noctx_ba_col] else "否",
            axis=1
        )

    elif preferred == "svo":
        df[f"ctx_prefer_{metric}"] = df.apply(
            lambda r: "正确_SVO" if r[svo_col] < r[ba_col] else "错误_把字句",
            axis=1
        )
        df["ctx_prefer_first_token"] = df.apply(
            lambda r: "正确_SVO" if r["ctx_svo_first_token_surp"] < r["ctx_ba_first_token_surp"] else "错误_把字句",
            axis=1
        )
        df[f"noctx_prefer_{metric}"] = df.apply(
            lambda r: "SVO" if r[noctx_svo_col] < r[noctx_ba_col] else "把字句",
            axis=1
        )
        df[f"context_helped_{metric}"] = df.apply(
            lambda r: "是" if r[svo_col] < r[noctx_svo_col] else "否",
            axis=1
        )

    else:
        raise ValueError("preferred must be 'ba' or 'svo'")

    return df


def summarize_result(df_ba: pd.DataFrame, df_svo: pd.DataFrame, model_alias: str, metric: str = "mean") -> Dict:
    ba_ctx_acc = (df_ba[f"ctx_prefer_{metric}"] == "正确_把字句").mean()
    ba_first_acc = (df_ba["ctx_prefer_first_token"] == "正确_把字句").mean()
    ba_noctx_rate = (df_ba[f"noctx_prefer_{metric}"] == "把字句").mean()
    ba_context_help = (df_ba[f"context_helped_{metric}"] == "是").mean()

    svo_ctx_acc = (df_svo[f"ctx_prefer_{metric}"] == "正确_SVO").mean()
    svo_first_acc = (df_svo["ctx_prefer_first_token"] == "正确_SVO").mean()
    svo_noctx_rate = (df_svo[f"noctx_prefer_{metric}"] == "SVO").mean()
    svo_context_help = (df_svo[f"context_helped_{metric}"] == "是").mean()

    summary = {
        "model": model_alias,
        "decision_metric": metric,

        "ba_group_ctx_sentence_acc": ba_ctx_acc,
        "ba_group_ctx_first_token_acc": ba_first_acc,
        "ba_group_noctx_ba_rate": ba_noctx_rate,
        "ba_group_context_help_rate": ba_context_help,

        "svo_group_ctx_sentence_acc": svo_ctx_acc,
        "svo_group_ctx_first_token_acc": svo_first_acc,
        "svo_group_noctx_svo_rate": svo_noctx_rate,
        "svo_group_context_help_rate": svo_context_help,

        "macro_ctx_sentence_acc": (ba_ctx_acc + svo_ctx_acc) / 2,
        "macro_ctx_first_token_acc": (ba_first_acc + svo_first_acc) / 2,
    }

    if "macbert_miss_svo" in df_ba.columns:
        summary["macbert_svo_miss_rate_in_ba_group"] = (df_ba["macbert_miss_svo"] == "漏检_认为SVO正确").mean()

    if "macbert_miss_ba" in df_svo.columns:
        summary["macbert_ba_miss_rate_in_svo_group"] = (df_svo["macbert_miss_ba"] == "漏检_认为把字句正确").mean()

    return summary


def safe_name(name: str) -> str:
    return re.sub(r"[^A-Za-z0-9_.-]+", "_", name)


def run_one_model(spec: Dict) -> Dict:
    alias = spec["alias"]
    model_id = spec["model_id"]
    quant = spec.get("quant", DEFAULT_QUANT)
    batch_size = spec.get("batch_size", 4)

    print(f"\n{'=' * 80}")
    print(f"[开始评测] {alias} | {model_id} | quant={quant} | batch_size={batch_size}")
    print(f"{'=' * 80}")

    tokenizer, model = load_tokenizer_and_model(model_id, quant=quant)

    try:
        # BA preferred group
        print(f"\n[{alias}] BA偏好组 scoring...")
        df_ba = df_ba_base.copy()
        ba_items = build_score_items_for_df(df_ba)
        ba_scores = score_items(model, tokenizer, ba_items, batch_size=batch_size)
        df_ba = attach_scores(df_ba, ba_scores)
        df_ba = add_preference_columns(df_ba, preferred="ba", metric=DECISION_METRIC)
        df_ba["model"] = alias
        df_ba["model_id"] = model_id

        # SVO preferred group
        print(f"\n[{alias}] SVO偏好组 scoring...")
        df_svo = df_svo_base.copy()
        svo_items = build_score_items_for_df(df_svo)
        svo_scores = score_items(model, tokenizer, svo_items, batch_size=batch_size)
        df_svo = attach_scores(df_svo, svo_scores)
        df_svo = add_preference_columns(df_svo, preferred="svo", metric=DECISION_METRIC)
        df_svo["model"] = alias
        df_svo["model_id"] = model_id

        # summary
        summary = summarize_result(df_ba, df_svo, model_alias=alias, metric=DECISION_METRIC)
        print_summary(summary)

        # save
        name = safe_name(alias)
        ba_path = os.path.join(OUTPUT_DIR, f"{name}_ba_preferred_results.csv")
        svo_path = os.path.join(OUTPUT_DIR, f"{name}_svo_preferred_results.csv")

        df_ba.to_csv(ba_path, index=False, encoding="utf-8-sig")
        df_svo.to_csv(svo_path, index=False, encoding="utf-8-sig")

        print(f"[保存] {ba_path}")
        print(f"[保存] {svo_path}")

        summary["ba_csv"] = ba_path
        summary["svo_csv"] = svo_path
        return summary

    finally:
        print(f"\n[清理显存] {alias}")
        del model
        del tokenizer
        cuda_empty_cache()


