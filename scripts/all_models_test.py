def clean_option(text: str) -> str:
    """清理候选项：删除 ✅、多余空格、句末标点。"""
    text = text.replace("✅", "").strip()
    text = re.sub(r"\s+", "", text)
    text = text.strip("。.!！?？")
    return text


def split_options(options_part: str) -> List[str]:
    """
    兼容以下形式：
    （A✅）/（B）
    （A✅）（B）
    (A ✅ / B)
    """
    s = options_part.strip()
    s = s.replace("（", "(").replace("）", ")")
    chunks = re.findall(r"\(([^()]*)\)", s)

    pieces = []
    if chunks:
        for ch in chunks:
            subparts = re.split(r"\s*/\s*", ch)
            pieces.extend([p.strip() for p in subparts if p.strip()])
    else:
        s = re.sub(r"[()]", "", s)
        pieces = [p.strip() for p in re.split(r"\s*/\s*", s) if p.strip()]

    return pieces


def parse_data(raw_str: str, is_ba_dataset: bool) -> List[Dict]:
    """
    is_ba_dataset=True:
        ✅ 项是 ba_sent，另一项是 svo_sent
    is_ba_dataset=False:
        ✅ 项是 svo_sent，另一项是 ba_sent
    """
    data = []
    current_type = ""
    example_id = 0

    for raw_line in raw_str.strip().split("\n"):
        line = raw_line.strip()
        if not line:
            continue

        if line.startswith("(情况") or line.startswith("（情况"):
            if is_ba_dataset:
                current_type = "物理状态改变" if "1" in line else "空间位移"
            else:
                current_type = "习惯性动作与泛指" if "1" in line else "叙述经历和日程"
            continue

        if "……" not in line:
            continue

        context_part, options_part = line.split("……", 1)

        m = re.match(r"^例\s*(\d+)\s*[:：]\s*(.*)$", context_part.strip())
        if m:
            local_id = int(m.group(1))
            context = m.group(2).strip()
        else:
            example_id += 1
            local_id = example_id
            context = context_part.strip()

        pieces = split_options(options_part)

        preferred = None
        nonpreferred = None
        for p in pieces:
            if "✅" in p:
                preferred = clean_option(p)
            else:
                # 只取第一个非 ✅ 项
                if nonpreferred is None:
                    nonpreferred = clean_option(p)

        if preferred is None or nonpreferred is None:
            print("[解析警告] 未能解析：", line)
            continue

        if is_ba_dataset:
            ba_sent = preferred
            svo_sent = nonpreferred
            gold = "ba"
            dataset = "ba_preferred"
        else:
            svo_sent = preferred
            ba_sent = nonpreferred
            gold = "svo"
            dataset = "svo_preferred"

        data.append({
            "dataset": dataset,
            "type": current_type,
            "example_id": local_id,
            "context": context,
            "ba_sent": ba_sent,
            "svo_sent": svo_sent,
            "gold": gold
        })

    return data


